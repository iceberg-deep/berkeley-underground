#!/bin/sh
# Stage 4: plant the real weaknesses + breadcrumbs + loot into the installed box.
#
# We cannot mount the guest's UFS from this host, so we stage everything into a
# tar, hand that tar to the guest as a raw second disk, boot the guest, and let
# inject-guest.sh (running as root inside) do the planting.  This host side only
# prepares the payload tar and drives the guest session (build/drive_guest.py).
set -eu
. "$(dirname "$0")/lib.sh"

[ -f "$IMAGE" ] || die "no installed image $IMAGE (run: make install)"
need openssl   # py3.13 dropped crypt(); we hash passwords with openssl on the host

STAGE="$WORK_DIR/inject-stage"
TAR="$WORK_DIR/inject-payload.tar"
rm -rf "$STAGE"; mkdir -p "$STAGE/files" "$STAGE/artifacts" "$STAGE/loot"

# ── build the loot tarball (flag inside) ───────────────────────────────────────
log "building loot tarball"
sh "$PAYLOAD_DIR/loot/build-loot.sh"
cp "$PAYLOAD_DIR/loot/$BOX_LOOT_NAME" "$STAGE/loot/$BOX_LOOT_NAME"

# ── password hashes (MD5 crypt; 2.2.8 understands $1$) ─────────────────────────
# Deterministic salts -> reproducible image.  These are THROWAWAY lab passwords.
hash() { openssl passwd -1 -salt "$1" "$2"; }
FOOTHOLD_HASH=$(hash bu01brian "$BOX_FOOTHOLD_PASS")
TRUST_HASH=$(hash    bu01donox "$BOX_TRUST_PASS")

# ── guest config (keeps config/box.env the single source of truth) ─────────────
cat > "$STAGE/box-guest.env" <<EOF
# generated by build/40-inject.sh — do not edit
FOOTHOLD_USER="$BOX_FOOTHOLD_USER"
FOOTHOLD_UID="104"
FOOTHOLD_HASH='$FOOTHOLD_HASH'
PEI_USER="pei"
PEI_UID="103"
PEI_HASH='*'
TRUST_USER="$BOX_TRUST_USER"
TRUST_UID="105"
TRUST_HASH='$TRUST_HASH'
LOOT_NAME="$BOX_LOOT_NAME"
LOOT_DIR="$BOX_LOOT_DIR"
HOSTNAME_FQDN="$BOX_HOSTNAME.$BOX_DOMAIN"
GUEST_IFACE="ed1"
GUEST_IP="10.0.2.15"
GUEST_GW="10.0.2.2"
EOF

# ── stage payload files + the guest script as RUN.sh ───────────────────────────
cp "$PAYLOAD_DIR/inject-guest.sh"        "$STAGE/RUN.sh"
cp "$PAYLOAD_DIR/files/pei.bash_history" "$STAGE/files/"
cp "$PAYLOAD_DIR/files/handover.txt"     "$STAGE/files/"
cp "$PAYLOAD_DIR/files/rhosts"           "$STAGE/files/"
cp "$PAYLOAD_DIR/files/newgrp-trojan.c"  "$STAGE/files/"
cp "$PAYLOAD_DIR/files/ftp-welcome.txt"  "$STAGE/files/"
cp "$PAYLOAD_DIR/artifacts/in.pmd.c"     "$STAGE/artifacts/"
cp "$PAYLOAD_DIR/artifacts/EVIDENCE.md"  "$STAGE/artifacts/"

# ── pack the tar that will BE the guest's second disk ──────────────────────────
log "packing payload tar"
( cd "$STAGE" && tar cf "$TAR" . )
ok "payload tar: $TAR ($(wc -c < "$TAR") bytes)"

# ── drive the guest to unpack + run it as root ─────────────────────────────────
PY="python3"; [ -x "$REPO_ROOT/.venv/bin/python3" ] && PY="$REPO_ROOT/.venv/bin/python3"
"$PY" -c 'import pexpect' 2>/dev/null || die "pexpect missing (run: make deps)"

export BOX_IMAGE_ABS="$IMAGE"
export BOX_PAYLOAD_TAR="$TAR"
export BOX_SERIAL_LOG="$WORK_DIR/inject-serial.log"
export QEMU_BIN BOX_MACHINE BOX_CPU BOX_MEM_MB BOX_ROOT_PASS
log "driving guest inject session (slow: full multiuser boot under TCG)"
"$PY" "$REPO_ROOT/build/drive_guest.py" || die "guest inject session failed (see $BOX_SERIAL_LOG)"
ok "inject complete"
