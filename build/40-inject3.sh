#!/bin/sh
# Stage 4 (Box 3 "the pivot"): clone the Box 1 base and plant the found-sniffer-log
# + password-reuse mechanic.  No reinstall.  See docs/box3-design.md.
set -eu
export BOX_ENV_FILE=box3.env
export BOX_PAYLOAD_SUBDIR=payloads3
. "$(dirname "$0")/lib.sh"

need openssl
BASE="$REPO_ROOT/${BOX3_BASE_IMAGE:?set BOX3_BASE_IMAGE in box3.env}"
[ -f "$BASE" ] || die "no base image $BASE (build Box 1 first: make build)"

mkdirs
log "cloning base $BASE -> $IMAGE"
cp "$BASE" "$IMAGE"

REAL_FLAG=$(sh "$REPO_ROOT/build/flag.sh") || die "could not derive flag (set BOX_FLAG_SEED or secret/flag.seed)"

# MD5 ($1$) hashes — throwaway lab passwords.  root REUSES ops's password.
hash() { openssl passwd -1 -salt "$1" "$2"; }
OPS_HASH=$(hash bu03ops  "$BOX_OPS_PASS")
ROOT_HASH=$(hash bu03root "$BOX_ROOT_PASS")

STAGE="$WORK_DIR/inject3-stage"
TAR="$WORK_DIR/inject3-payload.tar"
rm -rf "$STAGE"; mkdir -p "$STAGE/files"

cat > "$STAGE/box-guest.env" <<EOF
# generated by build/40-inject3.sh — do not edit
FOOTHOLD_USER="$BOX_FOOTHOLD_USER"
TRUST_USER="$BOX_TRUST_USER"
HOSTNAME_FQDN="$BOX_HOSTNAME.$BOX_DOMAIN"
LOOT_DIR="$BOX_LOOT_DIR"
LOOT_NAME="$BOX_LOOT_NAME"
OPS_USER="$BOX_OPS_USER"
OPS_HASH='$OPS_HASH'
ROOT_HASH='$ROOT_HASH'
SNIFFLOG="$BOX_SNIFFLOG"
FLAG_REAL='$REAL_FLAG'
FLAG_DECOY='$BOX_FLAG_DECOY'
EOF

# The prior intruder's sunsniffer capture log — the win path.  Realistic sunsniffer
# output (first bytes of each captured session); the operator 'ops' logs in over
# cleartext FTP, exposing the password root also reuses.  A couple of decoy
# sessions (non-privileged users) sit around it so it isn't a one-line grep.
cat > "$STAGE/files/sunsniff.log" <<EOF
sunsniffer v1.3 -- (c) the management.  do NOT leave this here.

-- TCP/IP LOG -- TM: Tue Feb  7 02:51:09 1995 --
 PATH: ts2-14.escape.com(1043) => escape.com(telnet)
 STAT: Tue Feb  7 02:53:40 1995, 121 pkts, 410 bytes
 DATA: kpatel
     : sk8erB0i
     : pine
     : quit
-----------------

-- TCP/IP LOG -- TM: Tue Feb  7 03:14:22 1995 --
 PATH: pc-ops.escape.com(1055) => escape.com(ftp)
 STAT: Tue Feb  7 03:14:55 1995, 44 pkts, 168 bytes
 DATA: USER ops
     : PASS $BOX_OPS_PASS
     : SYST
     : CWD /var/spool/backups
     : QUIT
-----------------

-- TCP/IP LOG -- TM: Tue Feb  7 06:02:31 1995 --
 PATH: dialup-09.escape.com(1071) => escape.com(pop3)
 STAT: Tue Feb  7 06:02:48 1995, 19 pkts, 88 bytes
 DATA: USER mwong
     : PASS letmein95
-----------------
EOF

cp "$PAYLOAD_DIR/inject3-guest.sh"      "$STAGE/RUN.sh"
cp "$PAYLOAD_DIR/gen-flag.sh"           "$STAGE/gen-flag.sh"
cp "$PAYLOAD_DIR/sunsniffer.c"          "$STAGE/files/"
cp "$PAYLOAD_DIR/files/sniff-notes.txt" "$STAGE/files/"

log "packing payload tar"
( cd "$STAGE" && tar cf "$TAR" . )
ok "payload tar: $TAR ($(wc -c < "$TAR") bytes)"

PY="python3"; [ -x "$REPO_ROOT/.venv/bin/python3" ] && PY="$REPO_ROOT/.venv/bin/python3"
"$PY" -c 'import pexpect' 2>/dev/null || die "pexpect missing (run: make deps)"
export BOX_IMAGE_ABS="$IMAGE"
export BOX_PAYLOAD_TAR="$TAR"
export BOX_SERIAL_LOG="$WORK_DIR/inject3-serial.log"
export QEMU_BIN BOX_MACHINE BOX_CPU BOX_MEM_MB BOX_ROOT_PASS
log "driving guest inject session (slow: full multiuser boot under TCG)"
"$PY" "$REPO_ROOT/build/drive_guest.py" || die "guest inject session failed (see $BOX_SERIAL_LOG)"
ok "Box 3 inject complete -> $IMAGE"
