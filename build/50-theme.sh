#!/bin/sh
# Stage 5: apply the disclosed cosmetic SunOS costume (banners, hostname, the
# /vmunix symlink).  Same tar-on-raw-disk delivery as inject — see 40-inject.sh.
# Cosmetic only; the box stays FreeBSD underneath (README "banners lie").
set -eu
. "$(dirname "$0")/lib.sh"

[ -f "$IMAGE" ] || die "no installed image $IMAGE (run: make install)"
THEME_DIR="$PAYLOAD_DIR/theme/$BOX_THEME"
[ -d "$THEME_DIR" ] || die "missing theme dir $THEME_DIR"

STAGE="$WORK_DIR/theme-stage"
TAR="$WORK_DIR/theme-payload.tar"
rm -rf "$STAGE"; mkdir -p "$STAGE/theme"

cp "$PAYLOAD_DIR/theme-guest.sh" "$STAGE/RUN.sh"
cp "$THEME_DIR/motd"  "$STAGE/theme/motd"
cp "$THEME_DIR/issue" "$STAGE/theme/issue"
cat > "$STAGE/box-guest.env" <<EOF
# generated by build/50-theme.sh
HOSTNAME_FQDN="$BOX_HOSTNAME.$BOX_DOMAIN"
EOF

log "packing theme tar"
( cd "$STAGE" && tar cf "$TAR" . )

PY="python3"; [ -x "$REPO_ROOT/.venv/bin/python3" ] && PY="$REPO_ROOT/.venv/bin/python3"
"$PY" -c 'import pexpect' 2>/dev/null || die "pexpect missing (run: make deps)"

export BOX_IMAGE_ABS="$IMAGE"
export BOX_PAYLOAD_TAR="$TAR"
export BOX_SERIAL_LOG="$WORK_DIR/theme-serial.log"
export QEMU_BIN BOX_MACHINE BOX_CPU BOX_MEM_MB BOX_ROOT_PASS
log "driving guest theme session"
"$PY" "$REPO_ROOT/build/drive_guest.py" || die "guest theme session failed (see $BOX_SERIAL_LOG)"
ok "theme complete"
