#!/bin/sh
# Stage 4 (Box 2): turn a CLONE of the Box 1 base image into Box 2 "The Traced
# Call".  No fresh OS install — we copy the proven installed+costumed base, stage
# the Box-2 payload into a tar, hand it to the guest as a raw second disk, and let
# inject2-guest.sh (root, inside) neutralise Box 1's chain and plant Box 2.
set -eu
export BOX_ENV_FILE=box2.env          # select Box 2 params
export BOX_PAYLOAD_SUBDIR=payloads2   # select Box 2 payloads
. "$(dirname "$0")/lib.sh"

need openssl
BASE="$REPO_ROOT/${BOX2_BASE_IMAGE:?set BOX2_BASE_IMAGE in box2.env}"
[ -f "$BASE" ] || die "no base image $BASE (build Box 1 first: make build)"

# ── clone the proven base -> the Box 2 working image ───────────────────────────
mkdirs
log "cloning base $BASE -> $IMAGE"
cp "$BASE" "$IMAGE"

# ── derive the Box 2 flag off-box (uses box2 instance/suffix via BOX_ENV_FILE) ─
REAL_FLAG=$(sh "$REPO_ROOT/build/flag.sh") || die "could not derive flag (set BOX_FLAG_SEED or secret/flag.seed)"

# ── stage the payload tar ──────────────────────────────────────────────────────
STAGE="$WORK_DIR/inject2-stage"
TAR="$WORK_DIR/inject2-payload.tar"
rm -rf "$STAGE"; mkdir -p "$STAGE/files"

cat > "$STAGE/box-guest.env" <<EOF
# generated by build/40-inject2.sh — do not edit
FOOTHOLD_USER="$BOX_FOOTHOLD_USER"
TRUST_USER="$BOX_TRUST_USER"
INTRUDER_SRCHOST="$BOX_INTRUDER_SRCHOST"
LOOT_DIR="$BOX_LOOT_DIR"
ACCT_LOG="$BOX_ACCT_LOG"
WATCH_INTERVAL="$BOX_WATCH_INTERVAL"
LOGIN_MAGIC="$BOX_LOGIN_MAGIC"
HOSTNAME_FQDN="$BOX_HOSTNAME.$BOX_DOMAIN"
FLAG_REAL='$REAL_FLAG'
FLAG_DECOY='$BOX_FLAG_DECOY'
EOF

cp "$PAYLOAD_DIR/inject2-guest.sh"   "$STAGE/RUN.sh"
cp "$PAYLOAD_DIR/tripwire.sh"        "$STAGE/tripwire.sh"
cp "$PAYLOAD_DIR/zap.c"              "$STAGE/zap.c"
cp "$PAYLOAD_DIR/login-trojan.c"     "$STAGE/login-trojan.c"
cp "$PAYLOAD_DIR/files/cache-notes.txt" "$STAGE/files/"
cp "$PAYLOAD_DIR/files/awtmp.seed"      "$STAGE/files/"
cp "$PAYLOAD_DIR/files/motd.notice"     "$STAGE/files/"

log "packing payload tar"
( cd "$STAGE" && tar cf "$TAR" . )
ok "payload tar: $TAR ($(wc -c < "$TAR") bytes)"

# ── drive the guest to unpack + run it as root ─────────────────────────────────
PY="python3"; [ -x "$REPO_ROOT/.venv/bin/python3" ] && PY="$REPO_ROOT/.venv/bin/python3"
"$PY" -c 'import pexpect' 2>/dev/null || die "pexpect missing (run: make deps)"

export BOX_IMAGE_ABS="$IMAGE"
export BOX_PAYLOAD_TAR="$TAR"
export BOX_SERIAL_LOG="$WORK_DIR/inject2-serial.log"
export QEMU_BIN BOX_MACHINE BOX_CPU BOX_MEM_MB BOX_ROOT_PASS
log "driving guest inject session (slow: full multiuser boot under TCG)"
"$PY" "$REPO_ROOT/build/drive_guest.py" || die "guest inject session failed (see $BOX_SERIAL_LOG)"
ok "Box 2 inject complete -> $IMAGE"
